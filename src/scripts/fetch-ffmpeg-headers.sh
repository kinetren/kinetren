#!/usr/bin/env bash
# Vendoring of PUBLIC FFmpeg headers for majors 6/7/8.
# Only the structure types (layout) are needed — bindgen turns them into the version
# modules of kt-ffmpeg. Downloaded once and committed: the build needs no network.
set -eo pipefail
cd "$(dirname "$0")/.."
DEST=libs/kt-ffmpeg/vendor
LIBS="libavutil libavcodec libavformat libswscale libswresample"

fetch() { # fetch <major> <version>
    local major="$1"
    local ver="$2"
    local out="$DEST/ffmpeg-$major/include"
    [ -f "$out/libavcodec/avcodec.h" ] && { echo "ffmpeg-$major: already present"; return; }
    echo "== FFmpeg $ver -> $out"
    local tmp; tmp=$(mktemp -d)
    curl -sSL "https://ffmpeg.org/releases/ffmpeg-$ver.tar.xz" -o "$tmp/ff.tar.xz"
    # only *.h of the needed libraries
    tar -xJf "$tmp/ff.tar.xz" -C "$tmp" --wildcards \
        $(for l in $LIBS; do echo "ffmpeg-$ver/$l/*.h"; done)
    mkdir -p "$out"
    for l in $LIBS; do
        mkdir -p "$out/$l"
        cp "$tmp/ffmpeg-$ver/$l"/*.h "$out/$l/"
    done
    # avconfig.h/ffversion.h are generated by configure — we put in the minimal ones
    cat > "$out/libavutil/avconfig.h" <<'AVC'
/* generated by hand: the values are the same for all target platforms */
#ifndef AVUTIL_AVCONFIG_H
#define AVUTIL_AVCONFIG_H
#define AV_HAVE_BIGENDIAN 0
#define AV_HAVE_FAST_UNALIGNED 1
#endif
AVC
    rm -rf "$tmp"
    echo "   ok: $(find "$out" -name '*.h' | wc -l) headers"
}

fetch 6 6.1.1
fetch 7 7.1.1
fetch 8 8.0
echo "done: $DEST"
