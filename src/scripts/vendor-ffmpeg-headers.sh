#!/usr/bin/env bash
# Vendors the headers of one FFmpeg release for kt-ffmpeg's bindgen (change ffmpeg-9,
# design D1): `src/libs/kt-ffmpeg/vendor/ffmpeg-<major>/include/<lib>/*.h`.
#
# The headers come from the official source tarball, checked against a SHA-256 committed
# HERE. The `ffmpeg-test` stage of packaging/Dockerfile builds the FFmpeg the Linux tests
# load from the SAME tarball (its FFMPEG_VERSION/FFMPEG_SHA256 ARGs), so the types that
# compile the version module and the libraries that test it come from one file;
# src/scripts/dist-check.py (t866) keeps the two pins equal. Bump both together.
#
# Layout of the earlier majors: the top-level `.h` of the five libraries we load
# (internal ones too — public headers include some of them), plus `libavutil/avconfig.h`,
# which configure generates and which is written here by hand (its values are the same for
# every target we build). `SOURCE` records where the tree came from.
#
# The tarball's signature was checked by hand when the pin was set (ffmpeg-9 tasks.md 1.1).
#
# Usage:  scripts/vendor-ffmpeg-headers.sh [version sha256]   (default: the pin below)
# Needs:  curl, sha256sum, tar with xz
set -euo pipefail
cd "$(dirname "$0")/.." # src/

VERSION="${1:-9.0.2}"
SHA256="${2:-8c3850283eb25fa026482078a04051e0be17347b09ef81a0849bec15a96e002e}"
URL="https://ffmpeg.org/releases/ffmpeg-$VERSION.tar.xz"
MAJOR="${VERSION%%.*}"
DEST="libs/kt-ffmpeg/vendor/ffmpeg-$MAJOR"
LIBS="libavutil libswresample libswscale libavcodec libavformat"

WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT
echo "vendor-ffmpeg-headers: downloading $URL"
curl -fsSL --retry 5 -C - -o "$WORK/src.tar.xz" "$URL"
echo "$SHA256  $WORK/src.tar.xz" | sha256sum -c --status \
    || { echo "vendor-ffmpeg-headers: SHA-256 of $URL differs from $SHA256" >&2; exit 1; }
tar xf "$WORK/src.tar.xz" -C "$WORK"
SRC="$WORK/ffmpeg-$VERSION"

TMP="$DEST.partial-$$"
rm -rf "$TMP"
for lib in $LIBS; do
    mkdir -p "$TMP/include/$lib"
    cp "$SRC/$lib"/*.h "$TMP/include/$lib/"
done
cat > "$TMP/include/libavutil/avconfig.h" <<'EOF'
/* generated by hand: the values are the same for all target platforms */
#ifndef AVUTIL_AVCONFIG_H
#define AVUTIL_AVCONFIG_H
#define AV_HAVE_BIGENDIAN 0
#define AV_HAVE_FAST_UNALIGNED 1
#endif
EOF
cat > "$TMP/SOURCE" <<EOF
FFmpeg $VERSION headers, vendored by src/scripts/vendor-ffmpeg-headers.sh
$URL
sha256 $SHA256
EOF
rm -rf "$DEST"
mv "$TMP" "$DEST"
echo "vendor-ffmpeg-headers: $DEST ($(find "$DEST/include" -name '*.h' | wc -l) headers)"
